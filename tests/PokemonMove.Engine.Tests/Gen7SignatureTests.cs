namespace PokemonMove.Engine.Tests;

public sealed class Gen7SignatureTests
{
    [Fact]
    public void VerifiesIndependentUpstreamSaveSignature() => Assert.True(Gen7SaveSignature.VerifyPayload(KnownSignature, out _));
    [Fact]
    public void FixedWidthRsaHandlesLeadingZeroSignaturesAndDecodedIntegers()
    {
        var leadingZeroSignatures = 0;
        for (var i = 0; i < 1024; i++)
        {
            var input = new byte[128]; BinaryPrimitives.WriteInt32LittleEndian(input, i);
            Gen7SaveSignature.SignPayload(input);
            if (input[32] == 0) leadingZeroSignatures++;
            Assert.True(Gen7SaveSignature.VerifyPayload(input, out var decoded), $"Payload {i} failed");
            Assert.Equal(i, BinaryPrimitives.ReadInt32LittleEndian(decoded));
        }
        Assert.True(leadingZeroSignatures > 0);
    }
